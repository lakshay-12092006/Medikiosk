# GET AYUSH QUESTIONS
# ============================================================

def get_questions(opd_type: str, language: str = "Hindi"):
    """
    Return AYUSH case-taking questions according to language.

    MediKiosk is AYUSH-focused, so only AYUSH questions
    are returned. General Clinical questions are not included.
    """

    # Normalize values
    opd_type = opd_type.strip().lower()
    language = language.strip().lower()

    # Only AYUSH workflow is supported
    if opd_type not in ["ayush", "ayurveda"]:
        return []

    # English selected
    if language == "english":
        return AYUSH_QUESTIONS_ENGLISH

    # Hindi selected / default
    return AYUSH_QUESTIONS_HINDI